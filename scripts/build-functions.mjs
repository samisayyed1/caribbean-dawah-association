// Bundles functions-src/* into self-contained files so Netlify never needs `npm install`.
// netlify/functions/<name>.mjs are tiny hand-written wrappers that keep the route config
// readable by Netlify; netlify/lib/<name>-core.mjs is the generated bundle.
import { build } from 'esbuild';

const BANNER = '// GENERATED by scripts/build-functions.mjs from functions-src/. Do not edit by hand.';
for (const name of ['api', 'media']) {
  await build({
    entryPoints: [`functions-src/${name}.mjs`],
    outfile: `netlify/lib/${name}-core.mjs`,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    legalComments: 'inline',
    banner: { js: BANNER },
    logLevel: 'warning'
  });
  console.log('built netlify/lib/' + name + '-core.mjs');
}
